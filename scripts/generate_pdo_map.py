"""Generate the compact C++ type table from the reviewed PDO reference data."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPONENT = ROOT / "components" / "zehnder_comfoair_q"
SOURCE = COMPONENT / "pdo_mapping.json"
TARGET = COMPONENT / "pdo_types.h"
TYPES = {"CN_BOOL", "CN_UINT8", "CN_UINT16", "CN_UINT32", "CN_INT8", "CN_INT16", "CN_INT64"}


def render(mapping):
    entries = mapping["pdos"]
    ids = [entry["id"] for entry in entries]
    if ids != sorted(set(ids)):
        raise ValueError("PDO IDs must be unique and sorted")
    lines = [
        "// Generated by scripts/generate_pdo_map.py; edit pdo_mapping.json instead.",
        "// aiocomfoconnect revision: " + mapping["upstream_revision"],
        "#pragma once",
        "",
        '#include "pdo_decode.h"',
        "",
        "namespace zehnder_comfoair_q {",
        "",
        "struct PdoDefinition {",
        "    uint16_t id;",
        "    PdoType type;",
        "    PdoType alternate_type;",
        "};",
        "",
        "inline const PdoDefinition *find_pdo_definition(uint16_t id) {",
        "    static constexpr PdoDefinition definitions[] = {",
    ]
    for entry in entries:
        accepted = entry["accepted_types"]
        if len(accepted) > 2 or any(t not in TYPES for t in accepted):
            raise ValueError(f"Unsupported types for PDO {entry['id']}")
        if not accepted:
            continue
        first = accepted[0].removeprefix("CN_")
        second = accepted[1].removeprefix("CN_") if len(accepted) == 2 else "NONE"
        lines.append(f"        {{{entry['id']}, PdoType::{first}, PdoType::{second}}},")
    lines += [
        "    };",
        "    size_t first = 0, last = sizeof(definitions) / sizeof(definitions[0]);",
        "    while (first < last) {",
        "        const size_t middle = first + (last - first) / 2;",
        "        if (definitions[middle].id < id) first = middle + 1;",
        "        else last = middle;",
        "    }",
        "    return first < sizeof(definitions) / sizeof(definitions[0]) && definitions[first].id == id",
        "        ? &definitions[first] : nullptr;",
        "}",
        "",
        "inline bool decode_pdo(uint16_t id, const std::vector<uint8_t> &data, PdoValue &value) {",
        "    const auto *definition = find_pdo_definition(id);",
        "    if (definition == nullptr) return false;",
        "    if (data.size() == pdo_type_size(definition->type))",
        "        return decode_pdo_value(definition->type, data, value);",
        "    return definition->alternate_type != PdoType::NONE &&",
        "        decode_pdo_value(definition->alternate_type, data, value);",
        "}",
        "",
        "} // namespace zehnder_comfoair_q",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated table is stale")
    args = parser.parse_args()
    output = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != output:
            parser.error("pdo_types.h is stale; run scripts/generate_pdo_map.py")
    else:
        TARGET.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
