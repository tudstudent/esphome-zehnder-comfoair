"""Generate passive diagnostics for the explicitly classified unknown registry IDs."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "components/zehnder_comfoair_q/pdo_mapping.json"
TARGET = ROOT / "packages/unidentified_telemetry.yml"
UNIDENTIFIED_IDS = (33, 37, 53, 219, 321, 325, 337, 341, 384, 386, 400, 401, 402)


def render(mapping):
    entries = {entry["id"]: entry for entry in mapping["pdos"]}
    for pdo in UNIDENTIFIED_IDS:
        if entries[pdo]["type"] is None or entries[pdo]["registry_type"] is None:
            raise ValueError(f"PDO {pdo} has no declared registry type")
    lines = [
        "# Generated by scripts/generate_unidentified_telemetry.py.",
        "# Passive only: no startup requests, physical labels, units, or inferred scales.",
        "substitutions:",
        "  comfoair_canbus_id: comfoair_canbus",
        "",
        "text_sensor:",
    ]
    for pdo in UNIDENTIFIED_IDS:
        lines += [
            "  - platform: template",
            f"    id: unidentified_pdo_{pdo}",
            f'    name: "Unidentified PDO {pdo} (Decoded Integer)"',
            "    entity_category: diagnostic",
            "    disabled_by_default: true",
            "    update_interval: never",
        ]
    lines += [
        "",
        "canbus:",
        "  - id: !extend ${comfoair_canbus_id}",
        "    on_frame:",
        "      - can_id: 0x40",
        "        can_id_mask: 0x1e003fc0",
        "        use_extended_id: true",
        "        remote_transmission_request: false",
        "        then:",
        "          - lambda: |-",
        "              switch (id(comfoair)->get_pdo_id_from_can_id (can_id)) {",
    ]
    for pdo in UNIDENTIFIED_IDS:
        lines.append(f"                  comfoair_on_frame_case({pdo}, id(comfoair), unidentified_pdo_{pdo});")
    lines += ["              }", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            parser.error("unidentified_telemetry.yml is stale; regenerate it")
    else:
        TARGET.write_text(result, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
