"""Audit every reference entry against the actual package handlers."""

import argparse
import json
from pathlib import Path
import re

import yaml

ROOT = Path(__file__).resolve().parents[1]


class PackageLoader(yaml.SafeLoader):
    pass


PackageLoader.add_multi_constructor("!", lambda loader, tag, node: loader.construct_scalar(node))


def inventory():
    mapping = json.loads((ROOT / "components/zehnder_comfoair_q/pdo_mapping.json").read_text(encoding="utf-8"))
    handlers = {}
    for package in sorted((ROOT / "packages").glob("*.yml")):
        text = package.read_text(encoding="utf-8")
        if "on_frame:" not in text:
            continue
        ids = set()
        config = yaml.load(text, Loader=PackageLoader)
        for bus in config.get("canbus", []):
            for frame in bus.get("on_frame", []):
                code = "\n".join(action.get("lambda", "") for action in frame.get("then", []))
                code = re.sub(r"//[^\n]*|/\*.*?\*/", "", code, flags=re.DOTALL)
                ids |= {int(pdo) for pdo in re.findall(r"comfoair_on_frame_case\(\s*(\d+)", code)}
                ids |= {int(pdo) for pdo in re.findall(r"case\s+(\d+)\s*:", code)}
                # Exact-ID handlers such as timers/bitsets do not use switch cases.
                if (frame.get("can_id_mask", 0) & 0x1ffc000) == 0x1ffc000 and "publish" in code:
                    ids.add(int(frame["can_id"]) >> 14)
        for pdo in ids:
            handlers.setdefault(pdo, []).append(package.name)
    rows = []
    for entry in mapping["pdos"]:
        pdo = entry["id"]
        packages = handlers.get(pdo, [])
        status = "mapped" if packages else "untyped" if entry["type"] is None else "documented-only"
        rows.append({"id": pdo, "type": entry["type"], "registry": entry["registry_type"] is not None,
                     "status": status, "packages": packages, "description": entry["description"]})
    return rows, handlers


def render_report(rows):
    lines = ["# PDO Coverage Classification", "", "Generated by `scripts/check_pdo_coverage.py --report`.", "",
             "Coverage describes handlers, not hardware availability or verified physical meaning.",
             "The 13 `unidentified_telemetry.yml` entries are passive, unscaled integer text.",
             "ComfoCool requires an explicit installation declaration; ComfoFond is presence-gated.",
             "Documented-only entries are deliberately not enabled: they lack registry definitions",
             "and individually validated entity metadata/availability. No type is invented for PDO 69.",
             "Experimental PDOs 305/306 are outside this pinned reference and remain unitless raw diagnostics.", "",
             "| PDO | Declared Type | Registry | Classification | Handler Packages |",
             "| --- | --- | --- | --- | --- |"]
    for row in rows:
        classification = "passive diagnostic" if row["packages"] == ["unidentified_telemetry.yml"] else row["status"]
        packages = ", ".join(f"`{name}`" for name in row["packages"]) or "-"
        lines.append(f"| {row['id']} | {row['type'] or 'undeclared'} | {'yes' if row['registry'] else 'no'} | {classification} | {packages} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Require every registry entry to have a handler")
    parser.add_argument("--json", action="store_true", help="Emit the complete classification, not just totals")
    parser.add_argument("--report", action="store_true", help="Write the complete documentation table, or check it with --check")
    args = parser.parse_args()
    rows, handlers = inventory()
    missing = [row["id"] for row in rows if row["registry"] and row["status"] != "mapped"]
    known = {row["id"] for row in rows}
    summary = {"documented_ids": len(rows), "registry_ids": sum(row["registry"] for row in rows),
               "mapped_registry_ids": sum(row["registry"] and row["status"] == "mapped" for row in rows),
               "missing_registry_ids": missing,
               "documented_only_ids": [row["id"] for row in rows if row["status"] == "documented-only"],
               "untyped_ids": [row["id"] for row in rows if row["status"] == "untyped"],
               "experimental_nonreference_ids": sorted(set(handlers) - known)}
    if args.check and missing:
        parser.error(f"Unmapped registry IDs: {missing}")
    if args.report:
        path = ROOT / "docs/PDO-COVERAGE.md"
        report = render_report(rows)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != report:
                parser.error("PDO-COVERAGE.md is stale; regenerate with --report")
        else:
            path.write_text(report, encoding="utf-8", newline="\n")
    print(json.dumps({"summary": summary, "entries": rows} if args.json else summary, indent=2))


if __name__ == "__main__":
    main()
